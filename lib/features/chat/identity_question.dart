/// 身份问句识别（职管家 · 对话前置兜底）
///
/// 独立为纯函数模块：与 UI 解耦、可独立单测（工程铁律：模块最小化、可独立测试）。
///
/// **判定规则**：只有用户提问归一化后与白名单 [kIdentityQuestions] **整句完全相等**
/// 才认定为身份问句，由本地直接给出标准答复、不调用大模型。
///
/// 历史实现采用「含『你/您』+ 命中任意宽泛子串」匹配，会把
/// 「你能帮我介绍下这个岗位吗」「你能给我推荐一个 AI 产品经理的岗位吗」
/// 等正常业务提问误判为身份问题并返回固定话术。改为整句匹配后，
/// 只有真正的身份问句走本地兜底，业务提问一律交给模型。
///
/// 新增问法时，在 [kIdentityQuestions] 中追加一条即可；
/// 追加的内容必须与 [normalizeQuestion] 的输出形式一致（无标点、无空格、小写）。
library;

/// 判断是否为身份类问题
bool isIdentityQuestion(String msg) {
  final cleaned = normalizeQuestion(msg);
  if (cleaned.isEmpty) return false;
  return kIdentityQuestions.contains(cleaned);
}

/// 归一化提问，便于整句比对：
/// 1. 转小写；
/// 2. 去掉所有非中文/字母/数字字符（标点、空白、表情、引号等）；
/// 3. 反复剥离「你好 / 请问 / 我想问一下」等开场白。
String normalizeQuestion(String msg) {
  var s = msg.toLowerCase().replaceAll(RegExp(r'[^\u4e00-\u9fa5a-z0-9]'), '');
  const prefixes = [
    '你好',
    '您好',
    '嗨',
    '哈喽',
    'hello',
    'hi',
    '请问',
    '我想问一下',
    '想问一下',
    '我想问',
    '想问',
    '问一下',
  ];
  var changed = true;
  while (changed) {
    changed = false;
    for (final p in prefixes) {
      if (s.startsWith(p) && s.length > p.length) {
        s = s.substring(p.length);
        changed = true;
      }
    }
  }
  return s;
}

